const STORAGE_KEY = 'studenthub_articles_data';

export function getStoredArticles() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Lỗi đọc bài viết từ localStorage:', e);
  }
  return INITIAL_ARTICLES;
}

export function saveArticle(newArticle) {
  const current = getStoredArticles();
  const articleObj = {
    id: newArticle.id || `art_${Date.now()}`,
    title: newArticle.title,
    category: newArticle.category || 'WIKI CAREER',
    categoryColor: newArticle.category === 'THƯ GIÃN' ? 'bg-amber-50 text-amber-700 border-amber-200' : 'bg-blue-50 text-blue-700 border-blue-200',
    imageUrl: newArticle.imageUrl || 'https://images.unsplash.com/photo-1554224155-8d04cb21cd6c?w=600&auto=format&fit=crop&q=80',
    summary: newArticle.summary,
    content: newArticle.content,
    author: newArticle.author || 'Ban Biên Tập StudentHub',
    publishedDate: newArticle.publishedDate || new Date().toLocaleDateString('vi-VN'),
    viewsCount: newArticle.viewsCount || 1
  };

  const filtered = current.filter(a => a.id !== articleObj.id);
  const updated = [articleObj, ...filtered];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new Event('studenthub_articles_updated'));
    }
  } catch (e) {}

  return updated;
}

export function deleteArticle(articleId) {
  const current = getStoredArticles();
  const updated = current.filter(a => a.id !== articleId);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new Event('studenthub_articles_updated'));
    }
  } catch (e) {}
  return updated;
}
